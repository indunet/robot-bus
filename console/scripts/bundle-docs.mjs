#!/usr/bin/env node
/**
 * Bake docs/zh + docs/en Markdown into a TS module for the console help page.
 * Runs as `prebuild` before `next build` (just console / pnpm build).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const SLUGS = [
  'rust-api',
  'python-api',
  'typescript-api',
  'cpp-api',
  'java-api',
  'android-api',
  'api-compare',
  'ros2-bridge',
  'perf-report',
  'ros2-perf-report',
]

const here = dirname(fileURLToPath(import.meta.url))
const consoleRoot = join(here, '..')
const repoRoot = join(consoleRoot, '..')
const outFile = join(consoleRoot, 'lib', 'bundled-docs.generated.ts')

function extractTitle(markdown, fallback) {
  const match = markdown.match(/^#\s+(.+)$/m)
  return match ? match[1].trim() : fallback
}

/** Drop the leading `[English](...) | 中文` row; the console has its own locale toggle. */
function stripLangSwitcher(markdown) {
  const lines = markdown.split(/\r?\n/)
  const first = (lines[0] ?? '').trim()
  if (/english/i.test(first) && first.includes('中文')) {
    lines.shift()
    if (lines[0] === '') lines.shift()
  }
  return lines.join('\n')
}

function readDoc(locale, slug) {
  const path = join(repoRoot, 'docs', locale, `${slug}.md`)
  let raw
  try {
    raw = readFileSync(path, 'utf8')
  } catch (err) {
    throw new Error(`missing docs/${locale}/${slug}.md (${err.message})`)
  }
  return stripLangSwitcher(raw)
}

const bundledDocs = SLUGS.map((slug) => {
  const zh = readDoc('zh', slug)
  const en = readDoc('en', slug)
  return {
    slug,
    titleZh: extractTitle(zh, slug),
    titleEn: extractTitle(en, slug),
    zh,
    en,
  }
})

const body = `/* eslint-disable */
// Generated by console/scripts/bundle-docs.mjs — do not edit.
export type BundledDoc = {
  slug: string
  titleZh: string
  titleEn: string
  zh: string
  en: string
}

export const bundledDocs: BundledDoc[] = ${JSON.stringify(bundledDocs, null, 2)}
`

writeFileSync(outFile, body)
console.log(`bundled ${bundledDocs.length} docs → lib/bundled-docs.generated.ts`)
